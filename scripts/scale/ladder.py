def evaluate(step: dict) -> tuple[str, list[str]]:
    """'pass' | 'fail' | 'inconclusive', and the reasons. Pure (tested).
    inconclusive = stopped for something that isn't a Baler ceiling."""
    reasons, other = [], []
    if step.get("live_safety_tripped"):
        other.append("live-safety: the live install on this host degraded; stopped (not a Baler ceiling)")
    if step.get("disk_low"):
        other.append("host disk low; stopped (not a Baler ceiling)")
    gen = step.get("generator", {})
    if gen.get("offered_ratio") is not None and gen["offered_ratio"] < MIN_GEN_RATIO:
        other.append(f"generator offered {gen['offered_ratio']:.1%} of target: a generator limit, not Baler's "
                     "(more --procs, or run it on another host)")
    if step.get("graph_timeout"):
        reasons.append(f"graph ingest: tags for {step['points']} points not in Oxigraph after {step['graph_timeout']} s")
    ing = step.get("ingest", {})
    if ing:
        ratio = ing.get("stored_ratio")
        if ratio is None or ratio < MIN_STORED_RATIO:
            reasons.append(f"data loss/backlog: stored {ratio if ratio is None else f'{ratio:.2%}'} of acknowledged readings "
                           f"(< {MIN_STORED_RATIO:.0%})")
        rate_ratio = ing.get("stored_rate_ratio")
        if rate_ratio is not None and rate_ratio < MIN_STORED_RATIO:
            reasons.append(f"stored rate {ing['stored_rps']:.0f}/s is {rate_ratio:.1%} of offered {ing['offered_rps']:.0f}/s")
        if (ing.get("broker_dropped_delta") or 0) > 0:
            # Broker-wide: with stored == acked these are QoS 0 deliveries to
            # the other full-telemetry subscribers (fault_detector, derivation_
            # engine) - history is intact, but Cur-mode rules and derivations
            # silently missed readings: not graceful, not visible.
            reasons.append(f"broker dropped {ing['broker_dropped_delta']} deliveries (a subscriber can't keep up: "
                           "the listener if readings are missing, else fault_detector/derivation_engine missed readings)")
    for svc, r in (step.get("rules") or {}).items():
        feed = r.get("feed") or {}
        if feed.get("missed_readings_delta"):
            reasons.append(f"{svc} missed {feed['missed_readings_delta']} readings (fell more than the reading feed's "
                           "retention behind)")
        elif (feed.get("lag_s_last") or 0) > MAX_P95_LAG_S:
            reasons.append(f"{svc} is {feed['lag_s_last']} s behind on the reading feed at the end of the soak")
    lag = step.get("lag", {})
    if lag:
        if lag.get("lost"):
            reasons.append(f"{lag['lost']} lag canaries never stored")
        if lag.get("p95_s") is None or lag["p95_s"] >= MAX_P95_LAG_S:
            reasons.append(f"p95 ingest lag {lag.get('p95_s')} s (>= {MAX_P95_LAG_S:.0f} s)")
        elif lag.get("last_third_median_s", 0) > lag.get("first_third_median_s", 0) + 10:
            reasons.append(f"growing backlog: lag median {lag['first_third_median_s']} s -> {lag['last_third_median_s']} s")
    for p in step.get("probes", []):
        if p.get("skipped"):
            continue
        if p["status"] != 200:
            reasons.append(f"probe {p['name']}: HTTP {p['status']}")
        elif p["median_s"] > p["budget_s"]:
            reasons.append(f"probe {p['name']}: median {p['median_s']} s > budget {p['budget_s']} s ({p['source']})")
        elif p.get("max_bytes") and p["bytes"] > p["max_bytes"]:
            reasons.append(f"probe {p['name']}: {p['bytes']} bytes > {p['max_bytes']}")
    for child, n in ((step.get("listener") or {}).get("restarts_delta") or {}).items():
        reasons.append(f"mqtt_listener {child} restarted {n}x")
    storm = step.get("tags_storm") or {}
    if storm.get("lag_p95_s") is not None and storm["lag_p95_s"] >= MAX_P95_LAG_S:
        reasons.append(f"tags storm of {storm['points']} points pushed p95 ingest lag to {storm['lag_p95_s']} s")
    for svc, c in step.get("containers", {}).items():
        if c.get("restarts_delta"):
            reasons.append(f"{svc} restarted {c['restarts_delta']}x" + (" (OOM-killed)" if c.get("oom_killed") else ""))
        elif c.get("oom_killed"):
            reasons.append(f"{svc} OOM-killed")
        elif c.get("status") not in (None, "running") and svc != "migrate":
            reasons.append(f"{svc} {c['status']} (exit {c.get('exit_code')})")
    if other:
        return "inconclusive", other + reasons
    return ("fail" if reasons else "pass"), reasons


# ----------------------------------------------------------------- one step

def run_step(ep: Endpoints, args, points: int, prev: int, budgets: dict, safety: LiveSafety, outdir: Path) -> dict:
    shape = common.Shape(points, args.points_per_equip, args.equips_per_site)
    step: dict = {"points": points, "offered_target_rps": points / args.interval, "sites": shape.sites,
                  "equips": shape.equips, "started": datetime.now(timezone.utc).isoformat()}
    print(f"\n=== step {points:,} points ({shape.sites} sites, {shape.equips} equips) ===", flush=True)
    conn = pg_connect(ep)
    states0 = container_states()

    # 1. tags + equips for the new points, then wait for the graph
    t0 = time.time()
    stats_file = outdir / f"gen-tags-{points}.json"
    gen = start_loadgen(ep, args, points, "tags", stats_file, tags_from=prev)
    gen.wait()
    tags_sent = read_stats(stats_file).get("sent", 0)
    deadline = t0 + args.graph_timeout
    g = {}
    while time.time() < deadline:
        g = graph_counts(ep)
        if g["scale_points"] >= points:
            break
        time.sleep(5)
    step["graph"] = {"tags_messages": tags_sent, "ingest_s": round(time.time() - t0, 1), **g}
    step["graph"]["tags_per_s"] = round(tags_sent / max(step["graph"]["ingest_s"], 1e-9), 1)
    if g.get("scale_points", 0) < points:
        step["graph_timeout"] = args.graph_timeout
        step["status"], step["reasons"] = evaluate(step)
        return step
    print(f"graph: {g['scale_points']} points in {step['graph']['ingest_s']} s", flush=True)

    # 2. readings: warm-up, then soak while sampling
    stats_file = outdir / f"gen-readings-{points}.json"
    gen = start_loadgen(ep, args, points, "readings", stats_file)
    sysmon = Sys(ep)
    canary = Canary(ep)
    samples: list[dict] = []
    try:
        time.sleep(args.warmup)
        soak_start = time.time()
        w0 = chunk_writes(conn)
        sys0 = sysmon.snapshot()
        feed0 = feed_status(conn)
        lst0 = listener_status(conn)
        storm = start_tags_storm(ep, args, points, outdir) if args.tags_storm else None
        hb: dict[str, list[datetime]] = {}
        while time.time() - soak_start < args.soak:
            time.sleep(args.sample_every)
            tripped, live = safety.check()
            st = read_stats(stats_file)
            sample = {"t": round(time.time() - soak_start, 1), "live": live, "stored_total": chunk_writes(conn),
                      "gen_rate": round(st.get("sent_rate_10s", 0)), "gen_behind_s": round(st.get("behind_s", 0), 1),
                      "broker": sysmon.snapshot(), "docker": docker_stats(), "lag": canary.stats(soak_start),
                      "feed": feed_status(conn), "listener": listener_status(conn)}
            t1 = time.perf_counter()
            conn.execute("SELECT 1")
            sample["pg_roundtrip_s"] = round(time.perf_counter() - t1, 4)
            for svc, at in conn.execute("SELECT service, beat_at FROM service_heartbeats"):
                if not hb.get(svc) or hb[svc][-1] != at:
                    hb.setdefault(svc, []).append(at)
            samples.append(sample)
            free_gb = shutil.disk_usage(common.REPO).free / 1e9
            lag_now = sample["lag"].get("max_s") or 0
            print(f"  t={sample['t']:>6}s gen {sample['gen_rate']}/s lag p95 {sample['lag'].get('p95_s')} s "
                  f"live {live} disk {free_gb:.1f} GB", flush=True)
            if tripped:
                step["live_safety_tripped"] = live
                break
            if free_gb < args.min_free_gb:
                step["disk_low"] = round(free_gb, 1)
                break
            states = container_states()
            if any(states.get(s, {}).get("restarts", 0) > c.get("restarts", 0) for s, c in states0.items()):
                break  # graceful-degradation failure: stop soaking, evaluate
            if lag_now > args.abort_lag:
                break
        soak_end = time.time()
        w1 = chunk_writes(conn)
        sys1 = sysmon.snapshot()
        feed1 = feed_status(conn)
        lst1 = listener_status(conn)
        if storm is not None:
            step["tags_storm"] = finish_tags_storm(storm, ep, points, args.tags_storm, canary)

        # 3. read probes and rules, still under load
        s = session(ep)
        ctx = {}
        t_cx = time.time()
        try:
            ctx["cx_project"] = ensure_cx_project(ep, s, shape)
        except Exception as exc:  # noqa: BLE001 - a Cx failure is a result
            step["cx_error"] = repr(exc)[:300]
        step["cx_run_s"] = round(time.time() - t_cx, 1)
        step["probes"] = run_probes(ep, s, budgets, ctx)
        step["graph"].update(graph_counts(ep))
        step["rules"] = {svc: {"cycles": len(v) - 1,
                               "median_cycle_s": round(statistics.median(
                                   [(b - a).total_seconds() for a, b in itertools.pairwise(v)]), 1) if len(v) > 2 else None}
                         for svc, v in hb.items()}
        # Rule daemons on the reading feed (#243): readings consumed per
        # second, how far behind they ran, and what they missed.
        details = heartbeat_details(conn)
        for svc, f1 in feed1.items():
            f0 = feed0.get(svc, {})
            lags = [x["feed"][svc]["lag_s"] for x in samples if svc in x.get("feed", {})]
            r = step["rules"].setdefault(svc, {})
            r["feed"] = {"missed_readings_delta": f1["missed_readings"] - f0.get("missed_readings", 0),
                         "lag_s_max": max(lags, default=None), "lag_s_last": f1["lag_s"],
                         "lag_readings_last": f1["lag_readings"]}
            r["heartbeat"] = details.get(svc)
    finally:
        gen.send_signal(signal.SIGTERM)
        try:
            gen.wait(timeout=60)
        except subprocess.TimeoutExpired:
            gen.kill()
        canary.drain(max_wait=args.abort_lag)
        canary.close()
        sysmon.close()

    # 4. what was stored vs what the broker acknowledged
    st = read_stats(stats_file)
    a, b = int(soak_start) + 1, int(soak_end)
    acked = acked_in(st, a, b)
    stored = stored_in(conn, a, b)
    dur = max(soak_end - soak_start, 1e-9)
    offered_rps = acked / max(b - a, 1)
    stored_rps = (w1 - w0) / dur
    dropped = None
    try:
        dropped = int(sys1.get("publish/messages/dropped", 0)) - int(sys0.get("publish/messages/dropped", 0))
    except (TypeError, ValueError):
        pass
    nproc = os.cpu_count() or 1
    caps = cpu_caps(nproc, common.read_env())
    step["ingest"] = {"window_s": b - a, "acked": acked, "stored": stored,
                      "stored_ratio": round(stored / acked, 5) if acked else None,
                      "offered_rps": round(offered_rps, 1), "stored_rps": round(stored_rps, 1),
                      "stored_rate_ratio": round(stored_rps / offered_rps, 4) if offered_rps else None,
                      "stored_rps_per_host_cpu": round(stored_rps / nproc, 1),
                      "stored_rps_per_listener_cpu": round(stored_rps / float(caps.get("SCALE_CPUS_MQTT_LISTENER", 1)), 1),
                      "broker_dropped_delta": dropped,
                      "rows_per_day_at_this_rate": round(stored_rps * 86400)}
    step["generator"] = {"target_rps": points / args.interval, "achieved_rps": round(offered_rps, 1),
                         "offered_ratio": round(offered_rps / (points / args.interval), 4),
                         "behind_max_s": st.get("behind_max_s"), "procs": st.get("procs"), "cpu_s": st.get("cpu_s")}
    step["lag"] = canary.stats(soak_start)
    step["broker"] = sys1
    step["db"] = db_metrics(conn)
    if step["db"].get("bytes_per_row"):
        step["db"]["bytes_per_day_raw_at_this_rate"] = round(step["db"]["bytes_per_row"] * stored_rps * 86400)
    step["resources"] = summarize_docker(samples)
    step["listener"] = summarize_listener(samples, lst0, lst1)
    states1 = container_states()
    step["containers"] = {svc: {**c, "restarts_delta": c["restarts"] - states0.get(svc, {}).get("restarts", 0)}
                          for svc, c in states1.items()}
    step["samples"] = samples
    step["soak_s"] = round(dur, 1)
    step["status"], step["reasons"] = evaluate(step)
    conn.close()
    return step


def summarize_docker(samples: list[dict]) -> dict:
    out: dict = {}
    for s in samples:
        for svc, d in s.get("docker", {}).items():
            o = out.setdefault(svc, {"cpu_pct": [], "mem_pct": [], "mem": "", "block_io": ""})
            o["cpu_pct"].append(d["cpu_pct"])
            o["mem_pct"].append(d["mem_pct"])
            o["mem"], o["block_io"] = d["mem"], d["block_io"]
    return {svc: {"cpu_pct_mean": round(statistics.mean(o["cpu_pct"]), 1), "cpu_pct_max": round(max(o["cpu_pct"]), 1),
                  "mem_pct_max": round(max(o["mem_pct"]), 1), "mem_last": o["mem"], "block_io_last": o["block_io"]}
            for svc, o in out.items() if o["cpu_pct"]}


