class Endpoints:
    def __init__(self, config: dict):
        ports = common.published_ports(config)
        env = common.read_env()
        self.mqtt_port = ports["mosquitto"][1883]
        self.gateway = f"http://127.0.0.1:{ports['gateway'][80]}"
        self.oxigraph = f"http://127.0.0.1:{ports['oxigraph'][7878]}"
        user = env.get("BALER_PG_USER") or "baler"
