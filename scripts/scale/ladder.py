def parse_count(s: str) -> int:
    s = s.strip().lower()
    mult = 1
    if s.endswith("k"):
        mult, s = 1_000, s[:-1]
    elif s.endswith("m"):
        mult, s = 1_000_000, s[:-1]
    return int(float(s) * mult)


def default_steps(nproc: int) -> list[int]:
    return (SMALL_HOST_STEPS if nproc < 4 else []) + DEFAULT_STEPS


