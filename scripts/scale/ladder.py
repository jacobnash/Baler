def cpu_caps(nproc: int, env: dict[str, str]) -> dict[str, str]:
    """SCALE_CPUS_* clamped to the host: Docker refuses a container `cpus`
    above the CPUs the host has (nash-srv boots with one visible today)."""
    text = common.OVERRIDE.read_text()
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("cpus: ${SCALE_CPUS_"):
            var, default = line[len("cpus: ${"):-1].split(":-")
            want = float(os.environ.get(var) or env.get(var) or default)
            out[var] = f"{min(want, float(nproc)):g}"
    return out


def stack_env() -> dict[str, str]:
    env = dict(os.environ)
    env.update(cpu_caps(os.cpu_count() or 1, common.read_env()))
    return env


