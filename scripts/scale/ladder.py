def busy_ports(config: dict) -> list[int]:
    """Host ports the stack would publish that something already holds."""
    import socket

    running = compose("ps", "-q", check=False, capture=True).stdout.split()
    if running:
        return []  # our own stack holds them
    busy = []
    for ports in common.published_ports(config).values():
        for host in ports.values():
            with socket.socket() as sock:
                if sock.connect_ex(("127.0.0.1", host)) == 0:
                    busy.append(host)
    return busy


def cmd_up(args) -> Endpoints:
    config = guard()
    busy = busy_ports(config)
    if busy:
        raise SystemExit(f"host ports {busy} are in use (another stack?): set other SCALE_*_PORT values in {common.ENV_FILE}")
    build = [] if getattr(args, "no_build", False) else ["--build"]
    compose("up", "-d", *build, "--wait", "--wait-timeout", "600")
    ep = Endpoints(config)
    preflight(ep)
    session(ep)  # creates the org + admin on a fresh stack
    ensure_rules(ep)
    print(f"scale stack up: gateway {ep.gateway}, broker 127.0.0.1:{ep.mqtt_port}")
    return ep


def preflight(ep: Endpoints, timeout: float = 120.0) -> None:
    """One reading from the generator's account must reach point_history.
    mosquitto PUBACKs a publish its ACL denies, so without this a broken
    ACL looks like a perfectly healthy generator feeding nothing."""
    canary = Canary(ep, every=1.0, timeout=timeout)
    try:
        end = time.time() + timeout
        while time.time() < end and not canary.samples:
            time.sleep(1)
    finally:
        canary.close()
    if not canary.samples:
        raise SystemExit(f"preflight: a reading published as scalegen never reached point_history in {timeout:.0f} s "
                         "(broker ACL? listener down?)")
    print(f"preflight: generator -> broker -> listener -> postgres ok ({canary.samples[0][1]:.2f} s)")


def cmd_down(args) -> None:
    guard()
    extra = ["--rmi", "local"] if args.rmi else []
    compose("down", "-v", "--remove-orphans", *extra)
    print("scale stack and its volumes removed")


