def session(ep: Endpoints):
    import requests

    s = requests.Session()
    s.headers["Accept-Encoding"] = "gzip"
    for _ in range(120):
        try:
            r = s.post(f"{ep.gateway}/auth/orgs", json={"name": "scale", "admin_email": EMAIL, "admin_password": PASSWORD},
                       timeout=30)
            if r.status_code in (201, 409):
                break
        except requests.RequestException:
            pass
        time.sleep(1)
    r = s.post(f"{ep.gateway}/auth/login", json={"email": EMAIL, "password": PASSWORD}, timeout=30)
    r.raise_for_status()
    s.headers["Authorization"] = "Bearer " + r.json()["token"]
    return s


def ensure_rules(ep: Endpoints) -> None:
    """One Cur-mode rule (evaluated on every reading) and one His-mode rule
    (a sweep over every scale point each cycle) - the per-point rule load a
    real install carries. Bounds chosen so they don't fire on the
    generator's values; a fault storm would measure something else."""
    s = session(ep)
    have = {r.get("name") for r in s.get(f"{ep.gateway}/fault/rules", timeout=30).json()}
    for rule in (
        {"name": "scale-range", "mode": "cur", "type": "range", "applies_to": {"topic_glob": f"{SCALE_GLOB}/*"},
         "min": -1000.0, "max": 1000.0},
        {"name": "scale-stale", "mode": "his", "type": "stale", "applies_to": {"topic_glob": f"{SCALE_GLOB}/*"},
         "max_age_seconds": 3600},
    ):
        if rule["name"] not in have:
            s.post(f"{ep.gateway}/fault/rules", json=rule, timeout=30).raise_for_status()


def ensure_cx_project(ep: Endpoints, s, shape: common.Shape) -> str | None:
    """A Cx project over site 0 (points_per_equip x equips_per_site points,
    500 by default) and a completed run over the last hour, so the report
    probe has a realistic project to render. Returns the id."""
    name = "scale site 0"
    projects = s.get(f"{ep.gateway}/cx/projects", timeout=60).json()
    p = next((p for p in projects if p.get("name") == name), None)
    if p is None:
        r = s.post(f"{ep.gateway}/cx/projects", json={"name": name, "phase": "functional",
                                                      "settings": {"prefixes": [shape.site_prefix(0)]}}, timeout=60)
        r.raise_for_status()
        p = r.json()
    r = s.post(f"{ep.gateway}/cx/projects/{p['id']}/runs", json={"window_hours": 1}, timeout=120)
    if r.ok:
        run_id = r.json().get("id") or r.json().get("run_id")
        for _ in range(300):
            run = s.get(f"{ep.gateway}/cx/runs/{run_id}", timeout=60).json().get("run", {})
            if run.get("status") in ("completed", "failed"):
                break
            time.sleep(2)
    return p["id"]


def run_probes(ep: Endpoints, s, budgets: dict, ctx: dict) -> list[dict]:
    out = []
    for probe in budgets["probes"]:
        if probe.get("needs") and not ctx.get(probe["needs"]):
            out.append({"name": probe["name"], "skipped": f"no {probe['needs']}"})
            continue
        path = probe["path"].format(**ctx)
        times, size, status = [], 0, None
        for _ in range(budgets.get("runs", 5)):
            t0 = time.perf_counter()
            try:
                r = s.get(ep.gateway + path, params=probe["params"], timeout=120)
                size, status = len(r.content), r.status_code
            except Exception as exc:  # noqa: BLE001 - a timeout is a result, not a crash
                status = repr(exc)[:200]
            times.append(time.perf_counter() - t0)
        out.append({"name": probe["name"], "path": path, "status": status, "bytes": size,
                    "cold_s": round(times[0], 3), "median_s": round(statistics.median(times[1:] or times), 3),
                    "max_s": round(max(times), 3), "budget_s": probe["warm_median_s"], "max_bytes": probe.get("max_bytes"),
                    "source": probe["source"]})
    return out


